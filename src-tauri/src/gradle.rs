//! Gradle project detection.
//!
//! Detection is static: the settings and build scripts are read and matched
//! against well-known plugins, so the panel fills in instantly without
//! starting a Gradle daemon. Asking Gradle itself for the full task list is a
//! separate, slower call (`query_tasks`).

use serde::Serialize;
use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;

const SETTINGS_FILES: [&str; 2] = ["settings.gradle.kts", "settings.gradle"];
const BUILD_FILES: [&str; 2] = ["build.gradle.kts", "build.gradle"];
/// Build scripts larger than this are not generated by hand; skip them.
const MAX_SCRIPT_BYTES: u64 = 1024 * 1024;

#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct GradleTask {
    /// The task name without the project path, e.g. `run`.
    pub name: String,
    /// What Gradle is asked to run, e.g. `:app:run`.
    pub path: String,
    /// "run", "build", "test", "custom" or "other"; drives grouping and icons.
    pub kind: String,
    pub description: String,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GradleProject {
    /// The Gradle project path: `:` for the root, `:app` for a subproject.
    pub path: String,
    pub name: String,
    /// Folder relative to the workspace root, empty for the root project.
    pub dir: String,
    /// The build script relative to the workspace root, when there is one.
    pub build_file: Option<String>,
    /// Human-readable plugin names that were recognised, e.g. "Spring Boot".
    pub plugins: Vec<String>,
    pub tasks: Vec<GradleTask>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GradleInfo {
    pub detected: bool,
    pub root_name: String,
    pub has_wrapper: bool,
    pub settings_file: Option<String>,
    /// The command line prefix that runs Gradle in the workspace's shell.
    pub launcher: String,
    /// The terminal runs PowerShell on Windows and a POSIX shell elsewhere.
    pub windows: bool,
    pub projects: Vec<GradleProject>,
}

fn read_script(path: &Path) -> Option<String> {
    let meta = fs::metadata(path).ok()?;

    if !meta.is_file() || meta.len() > MAX_SCRIPT_BYTES {
        return None;
    }

    fs::read_to_string(path).ok()
}

fn first_existing(dir: &Path, names: &[&str]) -> Option<String> {
    names
        .iter()
        .find(|name| dir.join(name).is_file())
        .map(|name| name.to_string())
}

/// Drops `//` line comments and `/* */` blocks so commented-out plugins and
/// includes are not detected. String contents are left alone.
fn strip_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut chars = source.chars().peekable();
    let mut quote: Option<char> = None;

    while let Some(ch) = chars.next() {
        if let Some(open) = quote {
            out.push(ch);

            if ch == '\\' {
                if let Some(next) = chars.next() {
                    out.push(next);
                }
            } else if ch == open || ch == '\n' {
                quote = None;
            }

            continue;
        }

        match ch {
            '"' | '\'' => {
                quote = Some(ch);
                out.push(ch);
            }
            '/' if chars.peek() == Some(&'/') => {
                for next in chars.by_ref() {
                    if next == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            '/' if chars.peek() == Some(&'*') => {
                chars.next();
                let mut previous = '\0';

                for next in chars.by_ref() {
                    if previous == '*' && next == '/' {
                        break;
                    }
                    if next == '\n' {
                        out.push('\n');
                    }
                    previous = next;
                }
            }
            _ => out.push(ch),
        }
    }

    out
}

/// Every quoted string in `text`, in order.
fn quoted_strings(text: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut chars = text.chars();

    while let Some(ch) = chars.next() {
        if ch != '"' && ch != '\'' {
            continue;
        }

        let mut value = String::new();

        for next in chars.by_ref() {
            if next == ch {
                break;
            }
            value.push(next);
        }

        found.push(value);
    }

    found
}

/// The statement that begins at `start`: up to the matching `)` when it opens
/// with a parenthesis, otherwise to the end of the line.
fn statement_at(source: &str, start: usize) -> &str {
    let rest = &source[start..];
    let trimmed = rest.trim_start();

    if trimmed.starts_with('(') {
        let offset = rest.len() - trimmed.len();
        let mut depth = 0;

        for (index, ch) in trimmed.char_indices() {
            match ch {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        return &rest[..offset + index + 1];
                    }
                }
                _ => {}
            }
        }

        return rest;
    }

    // Groovy allows `include 'a',\n 'b'`, so follow trailing commas.
    let mut end = 0;

    for line in rest.split_inclusive('\n') {
        end += line.len();

        if !line.trim_end().ends_with(',') {
            break;
        }
    }

    &rest[..end]
}

/// Positions right after each occurrence of `keyword` as a whole word.
fn keyword_positions(source: &str, keyword: &str) -> Vec<usize> {
    let bytes = source.as_bytes();
    let mut positions = Vec::new();
    let mut from = 0;

    while let Some(found) = source[from..].find(keyword) {
        let start = from + found;
        let end = start + keyword.len();
        let before_ok = start == 0 || !is_ident(bytes[start - 1]);
        let after_ok = end >= bytes.len() || !is_ident(bytes[end]);

        if before_ok && after_ok {
            positions.push(end);
        }

        from = end;
    }

    positions
}

fn is_ident(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'.'
}

/// Subproject paths from `include(...)` statements, normalised to `:a:b`.
fn included_projects(settings: &str) -> Vec<String> {
    let mut projects = BTreeSet::new();

    for position in keyword_positions(settings, "include") {
        for value in quoted_strings(statement_at(settings, position)) {
            let trimmed = value.trim().trim_start_matches(':');

            if trimmed.is_empty() || trimmed.contains('$') {
                continue;
            }

            projects.insert(format!(":{trimmed}"));
        }
    }

    projects.into_iter().collect()
}

fn root_project_name(settings: &str) -> Option<String> {
    let position = settings.find("rootProject.name")?;
    let rest = &settings[position..];
    let line = rest.lines().next()?;

    quoted_strings(line).into_iter().next()
}

