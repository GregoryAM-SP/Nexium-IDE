/// The `application` plugin has no dotted id, so it gets its own check.
fn has_application_plugin(script: &str) -> bool {
    script.contains("\"application\"")
        || script.contains("'application'")
        || script.lines().any(|line| {
            let line = line.trim();
            line == "application"
                || line.starts_with("application {")
                || line.starts_with("application{")
        })
}

fn has_jvm_plugin(script: &str) -> bool {
    ["\"java\"", "'java'", "java-library", "kotlin(\"jvm\")", "org.jetbrains.kotlin", "kotlin-android", "\"groovy\"", "'groovy'", "\"scala\"", "'scala'"]
        .iter()
        .any(|marker| script.contains(marker))
        || script.lines().any(|line| {
            let line = line.trim();
            line == "java" || line == "`java-library`" || line == "`java`"
        })
}

/// Names of tasks declared in the script itself.
fn custom_tasks(script: &str) -> Vec<(String, bool)> {
    let mut tasks = Vec::new();
    let mut seen = BTreeSet::new();

    let mut push = |name: String, exec: bool| {
        let valid = !name.is_empty()
            && name
                .chars()
                .all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '-');

        if valid && seen.insert(name.clone()) {
            tasks.push((name, exec));
        }
    };

    // tasks.register("x"), tasks.register<JavaExec>("x"), tasks.create("x")
    for keyword in ["tasks.register", "tasks.create"] {
        let mut from = 0;

        while let Some(found) = script[from..].find(keyword) {
            let start = from + found + keyword.len();
            let statement: String = script[start..].chars().take(200).collect();
            let head = statement.split(['{', '\n']).next().unwrap_or("");

            if let Some(name) = quoted_strings(head).into_iter().next() {
                push(name, head.contains("JavaExec") || head.contains("Exec"));
            }

            from = start;
        }
    }

    // Groovy: `task hello { ... }`, `task hello(type: JavaExec)`, `task('hello')`
    for line in script.lines() {
        let line = line.trim();

        let Some(rest) = line.strip_prefix("task ").or_else(|| line.strip_prefix("task(")) else {
            continue;
        };

        let exec = rest.contains("Exec");
        let rest = rest.trim_start();

        let name = if rest.starts_with('"') || rest.starts_with('\'') {
            quoted_strings(rest).into_iter().next().unwrap_or_default()
        } else {
            rest.chars()
                .take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '_')
                .collect()
        };

        push(name, exec);
    }

    tasks
}

fn task_path(project: &str, name: &str) -> String {
    if project == ":" {
        name.to_string()
    } else {
        format!("{project}:{name}")
    }
}

fn analyse_project(root: &Path, path: &str) -> GradleProject {
    let dir = path.trim_start_matches(':').replace(':', "/");
    let folder = if dir.is_empty() {
        root.to_path_buf()
    } else {
        root.join(&dir)
    };
    let name = if path == ":" {
        root.file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_else(|| "root".into())
    } else {
        path.rsplit(':').next().unwrap_or(path).to_string()
    };

    let build_name = first_existing(&folder, &BUILD_FILES);
    let script = build_name
        .as_ref()
        .and_then(|file| read_script(&folder.join(file)))
        .map(|text| strip_comments(&text))
        .unwrap_or_default();

    let mut plugins = Vec::new();
    let mut tasks: Vec<GradleTask> = Vec::new();
    let mut add = |name: &str, kind: &str, description: &str| {
        if tasks.iter().any(|task| task.name == name) {
            return;
        }

        tasks.push(GradleTask {
            name: name.to_string(),
            path: task_path(path, name),
            kind: kind.to_string(),
            description: description.to_string(),
        });
    };

    for rule in PLUGIN_RULES {
        if rule.markers.iter().any(|marker| script.contains(marker)) {
            if !plugins.contains(&rule.label.to_string()) {
                plugins.push(rule.label.to_string());
            }

            for (task, kind, description) in rule.tasks {
                add(task, kind, description);
            }
        }
    }

    if has_application_plugin(&script) {
        plugins.push("Application".into());
        add("run", "run", "Run the application's main class");
    }

    let jvm = has_jvm_plugin(&script) || !plugins.is_empty();

    if jvm {
        if !plugins.iter().any(|label| label.starts_with("Android")) {
            plugins.insert(0, if script.contains("kotlin") { "Kotlin" } else { "Java" }.into());
        }

        add("test", "test", "Run the unit tests");
    }

    for (name, exec) in custom_tasks(&script) {
        add(
            &name,
            if exec { "run" } else { "custom" },
            if exec { "Custom exec task" } else { "Declared in the build script" },
        );
    }

    // Every Gradle project has these, but only real builds need the buttons.
    if build_name.is_some() {
        add("build", "build", "Assemble and test this project");
        add("clean", "build", "Delete the build directory");
    }

    let build_file = build_name.map(|file| {
        if dir.is_empty() {
            file
        } else {
            format!("{dir}/{file}")
        }
    });

    GradleProject {
        path: path.to_string(),
        name,
        dir,
        build_file,
        plugins,
        tasks,
    }
}

#[cfg(windows)]
fn launcher(has_wrapper: bool) -> String {
    // The terminal runs PowerShell, which needs the `.\` prefix.
    if has_wrapper { ".\\gradlew.bat".into() } else { "gradle".into() }
}

#[cfg(not(windows))]
fn launcher(has_wrapper: bool) -> String {
    if has_wrapper { "./gradlew".into() } else { "gradle".into() }
}

fn wrapper_present(root: &Path) -> bool {
    if cfg!(windows) {
        root.join("gradlew.bat").is_file()
    } else {
        root.join("gradlew").is_file()
    }
}

pub fn detect(root: &Path) -> GradleInfo {
    let settings_file = first_existing(root, &SETTINGS_FILES);
    let root_build = first_existing(root, &BUILD_FILES);
    let has_wrapper = wrapper_present(root);
    let detected = settings_file.is_some() || root_build.is_some();

    let settings = settings_file
        .as_ref()
        .and_then(|file| read_script(&root.join(file)))
        .map(|text| strip_comments(&text))
        .unwrap_or_default();

    let root_name = root_project_name(&settings).unwrap_or_else(|| {
        root.file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default()
    });

    let projects = if detected {
        std::iter::once(":".to_string())
            .chain(included_projects(&settings))
            .map(|path| analyse_project(root, &path))
            // An included project without its own script and without tasks
            // contributes nothing but noise.
            .filter(|project| project.path == ":" || project.build_file.is_some())
            .map(|mut project| {
                if project.path == ":" {
                    project.name = root_name.clone();
                }
                project
            })
            .collect()
    } else {
        Vec::new()
    };

    GradleInfo {
        detected,
        root_name,
        has_wrapper,
        settings_file,
        launcher: launcher(has_wrapper),
        windows: cfg!(windows),
        projects,
    }
}

/// Parses the output of `gradle tasks --all`: group headings followed by a
/// dashed rule, then `path - description` lines.
fn parse_task_listing(output: &str) -> Vec<GradleTask> {
    let mut tasks = Vec::new();
    let mut group = String::new();
    let lines: Vec<&str> = output.lines().collect();

    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim();

        if lines
            .get(index + 1)
            .is_some_and(|next| next.trim().len() >= 3 && next.trim().chars().all(|ch| ch == '-'))
        {
            group = trimmed.trim_end_matches(" tasks").to_lowercase();
            continue;
        }

        if trimmed.is_empty()
            || trimmed.chars().all(|ch| ch == '-')
            || group.is_empty()
            || group.starts_with("rules")
            || line.starts_with(char::is_whitespace)
        {
            continue;
        }

        let (path, description) = match trimmed.split_once(" - ") {
            Some((path, description)) => (path.trim(), description.trim()),
            None => (trimmed, ""),
        };

        if path.contains(' ') || path.is_empty() {
            continue;
        }

        let name = path.rsplit(':').next().unwrap_or(path).to_string();
        let kind = match group.as_str() {
            "application" => "run",
            "build" => "build",
            "verification" => "test",
            "other" => "other",
            _ if name.starts_with("run") || name == "bootRun" => "run",
            _ => "custom",
        };

        tasks.push(GradleTask {
            name,
            path: path.to_string(),
            kind: kind.to_string(),
            description: if description.is_empty() {
                format!("{} task", group)
            } else {
                description.to_string()
            },
        });
    }

    tasks
}

/// Asks Gradle for every task in the build. This starts (or reuses) a Gradle
/// daemon and can take a while on the first call.
pub fn query_tasks(root: &Path, java_home: Option<&str>) -> Result<Vec<GradleTask>, String> {
    let mut command = if wrapper_present(root) {
        Command::new(root.join(if cfg!(windows) { "gradlew.bat" } else { "gradlew" }))
    } else {
        Command::new("gradle")
    };

    command
        .current_dir(root)
        .args(["tasks", "--all", "--console=plain", "-q"]);

    // The JDK picked in Project settings, for this machine only.
    if let Some(home) = java_home.filter(|home| !home.trim().is_empty()) {
        if !Path::new(home).is_dir() {
            return Err(format!("The Gradle JDK folder no longer exists: {home}"));
        }
        command.env("JAVA_HOME", home);
    }

    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        command.creation_flags(CREATE_NO_WINDOW);
    }

    let output = command.output().map_err(|error| {
        if error.kind() == std::io::ErrorKind::NotFound {
            "Gradle was not found. Add a Gradle wrapper or install Gradle on your PATH.".to_string()
        } else {
            format!("Gradle could not start: {error}")
        }
    })?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        // Gradle puts the useful line right after "* What went wrong:".
        let message = stderr
            .lines()
            .skip_while(|line| !line.starts_with("* What went wrong"))
            .nth(1)
            .or_else(|| stderr.lines().rev().find(|line| !line.trim().is_empty()))
            .unwrap_or("")
            .trim()
            .to_string();

        return Err(if message.is_empty() {
            "Gradle could not list the tasks.".into()
        } else {
            format!("Gradle could not list the tasks: {message}")
        });
    }

    Ok(parse_task_listing(&String::from_utf8_lossy(&output.stdout)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_kotlin_and_groovy_includes() {
        let kts = "rootProject.name = \"demo\"\ninclude(\":app\", \":libs:core\")\n// include(\":old\")";
        let stripped = strip_comments(kts);
        assert_eq!(included_projects(&stripped), vec![":app", ":libs:core"]);
        assert_eq!(root_project_name(&stripped).as_deref(), Some("demo"));

        let groovy = "include 'app',\n  'server'\nincludeBuild 'tools'";
        assert_eq!(included_projects(groovy), vec![":app", ":server"]);
    }

    #[test]
    fn finds_custom_tasks() {
        let script = "tasks.register<JavaExec>(\"runTool\") {\n}\ntasks.register(\"hello\") {}\ntask greet {\n}";
        let names: Vec<_> = custom_tasks(script);
        assert_eq!(
            names,
            vec![
                ("runTool".to_string(), true),
                ("hello".to_string(), false),
                ("greet".to_string(), false)
            ]
        );
    }

    #[test]
    fn detects_a_multi_project_build() {
        let root = std::env::temp_dir().join(format!("nexium-gradle-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(root.join("server")).unwrap();
        fs::create_dir_all(root.join("cli")).unwrap();
        fs::create_dir_all(root.join("lib")).unwrap();

        fs::write(
            root.join("settings.gradle.kts"),
            "rootProject.name = \"shop\"\ninclude(\":server\", \":cli\", \":lib\", \":missing\")\n",
        )
        .unwrap();
        fs::write(root.join("build.gradle.kts"), "plugins { base }\n").unwrap();
        fs::write(
            root.join("server/build.gradle.kts"),
            "plugins {\n  id(\"org.springframework.boot\") version \"3.3.0\"\n  kotlin(\"jvm\")\n}\n",
        )
        .unwrap();
        fs::write(
            root.join("cli/build.gradle"),
            "plugins {\n  id 'java'\n  id 'application'\n}\napplication { mainClass = 'shop.Main' }\n",
        )
        .unwrap();
        fs::write(root.join("lib/build.gradle.kts"), "plugins { `java-library` }\n// id(\"application\")\n").unwrap();

        let info = detect(&root);
        let _ = fs::remove_dir_all(&root);

        assert!(info.detected);
        assert_eq!(info.root_name, "shop");
        let paths: Vec<_> = info.projects.iter().map(|project| project.path.as_str()).collect();
        assert_eq!(paths, vec![":", ":cli", ":lib", ":server"]);

        let runnable = |path: &str| -> Vec<String> {
            info.projects
                .iter()
                .find(|project| project.path == path)
                .unwrap()
                .tasks
                .iter()
                .filter(|task| task.kind == "run")
                .map(|task| task.path.clone())
                .collect()
        };

        assert_eq!(runnable(":server"), vec![":server:bootRun"]);
        assert_eq!(runnable(":cli"), vec![":cli:run"]);
        assert!(runnable(":lib").is_empty(), "commented-out plugin was detected");
        assert!(runnable(":").is_empty());
    }

    #[test]
    fn parses_gradle_task_listing() {
        let output = "Application tasks\n-----------------\napp:run - Runs this project as a JVM application\n\nBuild tasks\n-----------\nassemble - Assembles the outputs of this project.\n\nOther tasks\n-----------\nhello\n";
        let tasks = parse_task_listing(output);
        assert_eq!(tasks.len(), 3);
        assert_eq!(tasks[0].path, "app:run");
        assert_eq!(tasks[0].kind, "run");
        assert_eq!(tasks[1].kind, "build");
        assert_eq!(tasks[2].name, "hello");
    }
}
